-- Фаза 2 «Реальність → система»: черга «Підтверди». Джері звіряє задачі з перепискою групи клієнта
-- і пропонує: задача схоже зроблена / нове прохання клієнта / записати в історію. Нічого не робить сам — тільки після ✓ Саші.
CREATE TABLE confirm_queue (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,                 -- task_done | task_new | log
  task_id INTEGER,                    -- для task_done
  title TEXT NOT NULL,
  evidence TEXT NOT NULL DEFAULT '',  -- цитата з повідомлення, дата, хто
  status TEXT NOT NULL DEFAULT 'new', -- new | ok | skip
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  decided_at TEXT
);
CREATE INDEX idx_confirm_queue ON confirm_queue(status, client_id);


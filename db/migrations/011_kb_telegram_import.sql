'# Коли робити
- Новий клієнт, а вся історія спілкування — в Telegram-групі чи особистому чаті.
- Бот Джері бачить тільки повідомлення після того, як його додали; старе — тільки через експорт.

# Де експорт
- Потрібен **Telegram Desktop** (https://desktop.telegram.org). Звичайний «Telegram» для Mac з App Store експорт НЕ вміє.

# Кроки
1. Відкрий потрібний чат у Telegram Desktop.
2. Вгорі справа **⋮** → **«Експорт історії чату»**.
3. Зніми галочки з фото, відео, файлів — потрібен тільки текст (так швидше і менший файл).
4. Формат: **«Машиночитний JSON»** → Експортувати → «Показати мої дані».
5. У системі: картка клієнта → **Налаштування клієнта** (або розділ Telegram) → **«Обрати файл експорту»** → файл `result.json` з папки експорту.
6. Натисни **«Джері, розбери історію і заповни картку»** — він внесе потреби, бюджет, домовленості, задачі.

# Нюанси
- Повторний імпорт того самого чату не дублює повідомлення.
- Якщо в групі вже є бот Джері — старі й нові повідомлення зливаються в одну історію.
- Голосові з експорту приходять без тексту (файлів у експорті нема) — буде позначка «голосове».
- Можна і HTML-експорт: обери всі файли `messages*.html` разом, але JSON надійніший.');

-- Доступи клієнта: ДЕ лежить доступ і чий він. Паролів тут нема і бути не може — тільки назва/посилання запису в Bitwarden.
CREATE TABLE client_access (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  client_id INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  service TEXT NOT NULL,                 -- KeyCRM, Meta Business, хостинг, домен, телефонія…
  login TEXT NOT NULL DEFAULT '',        -- логін / email (не пароль)
  url TEXT NOT NULL DEFAULT '',          -- куди заходити
  vault_name TEXT NOT NULL DEFAULT '',   -- назва запису в Bitwarden («Іванов — KeyCRM»)
  vault_url TEXT NOT NULL DEFAULT '',    -- пряме посилання на запис у веб-сейфі
  owner TEXT NOT NULL DEFAULT 'client',  -- client (акаунт клієнта) | mine (мій) | shared (спільний)
  twofa TEXT NOT NULL DEFAULT '',        -- де 2FA: «SMS на телефон клієнта», «мій Authenticator»…
  note TEXT NOT NULL DEFAULT '',
  checked_at TEXT,                       -- коли востаннє перевірили, що доступ живий
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  updated_at TEXT NOT NULL DEFAULT (datetime('now'))
);
CREATE INDEX client_access_client ON client_access(client_id);

